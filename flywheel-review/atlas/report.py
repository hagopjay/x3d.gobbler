#!/usr/bin/env python3
"""Write out/FINDINGS.md from out/findings.json and out/receipt.json. Every figure in it is read from those two files."""
import json
import pathlib

import os
OUT = pathlib.Path(os.environ.get("ATLAS_OUT", pathlib.Path(__file__).resolve().parent / "out"))
F = json.loads((OUT / "findings.json").read_text(encoding="utf-8"))
R = json.loads((OUT / "receipt.json").read_text(encoding="utf-8"))
A = json.loads((OUT / "atlas.json").read_text(encoding="utf-8"))
T = F["traceability"]
W = []
w = W.append


def table(head, rows):
    w("| " + " | ".join(head) + " |")
    w("|" + "---|" * len(head))
    for r in rows:
        w("| " + " | ".join(str(c) for c in r) + " |")
    w("")


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "n/a"


c = F["counts"]
w("# The Atlas, version 0: what the graph shows")
w("")
w(f"Generated by `report.py` from `findings.json` and `receipt.json`. Inputs: `x3d.loom@{R['inputs']['x3d.loom'][:7]}` "
  f"(`LOOM-v1.md`) and `x3d.docs@{R['inputs']['x3d.docs'][:7]}` (`docs/learn`, {c['Chapter']} chapters). "
  "Local files; nothing here was pushed.")
w("")
w("**How to read the grades here.** Counts and the witness results were computed by code in this folder and are "
  "repeatable (run `check_atlas.py`). Statements about what a row *means* (for example that an instrument string names "
  "no tool) are the builder's reading of free text, and are worklists to look at, not verdicts.")
w("")
w("## 1. What is in the graph")
w("")
table(["kind", "nodes"], [[k, v] for k, v in c.items()])
w(f"{sum(c.values())} nodes, {F['edge total']} edges. Edges by kind: "
  + ", ".join(f"{k} {v}" for k, v in F["edges"].items()) + ".")
w("")
w("## 2. The witness")
w("")
ok = sum(1 for x in R["checks"] if x["ok"])
w(f"`check_atlas.py`: **{ok} of {len(R['checks'])} checks pass** (rdflib {R['engine']['rdflib']}, Python {R['engine']['python']}; "
  f"claim checker `{R['engine']['checker']}`, schema `{R['engine']['schema']}`, strict pins).")
w("")
rows = []
for x in R["checks"]:
    d = {k: v for k, v in x.items() if k not in ("name", "ok") and not isinstance(v, (list, dict))}
    rows.append([x["name"], "pass" if x["ok"] else "**FAIL**", ", ".join(f"{k} {v}" for k, v in d.items())])
table(["check", "result", "detail"], rows)
cl = next(x for x in R["checks"] if x["name"].startswith("the family"))
w(f"The claims row is the one that matters most: x3d.docs' own checker read each source file at its pinned commit "
  f"({', '.join(f'{k} {v}' for k, v in cl['read'].items())}) and found every one of the {cl['claims']} values the Atlas copied "
  "inside its quote, on the line the Atlas names. That is a check of transcription, not of truth: it says the Atlas "
  "says what the ledgers say.")
w("")
w("## 3. What the graph shows")
w("")
w("### 3.1 Traceability reaches two chapters")
w("")
w(f"- {T['numbers with a verified quote']} of {T['numbers']} numbers ({pct(T['numbers with a verified quote'], T['numbers'])}) "
  f"have a quote the claim checker verified; {T['Confirmed numbers with a verified quote']} of the {T['Confirmed numbers']} "
  f"Confirmed ones ({pct(T['Confirmed numbers with a verified quote'], T['Confirmed numbers'])}).")
w(f"- Ledgers exist for chapters {', '.join(T['chapters with a ledger'])} only. {T['heuristics with a ledger quote']} heuristic "
  f"has a ledger line. Kinds of source: {', '.join(f'{k} {v}' for k, v in T['claims by kind of source'].items())}.")
w(f"- The {c['Claim']} claims stand on {len(T['pins the claims stand on'])} pins: "
  + ", ".join(f"`{p}`" for p in T["pins the claims stand on"]) + ".")
w("")
table(["chapter", "numbers", "with a quote", "verified"],
      [[ch, v["numbers"], v["quoted"], v["verified"]] for ch, v in T["by chapter"].items()])
w("### 3.2 Instruments: pointers and unnamed parts")
w("")
ni = F["number instruments"]
weak = F["Confirmed numbers with no pin and no versioned tool in their instrument"]
w(f"- {ni.get('inferred from the row above', 0)} of {T['numbers']} numbers write their instrument as a pointer (`same`, "
  "`same rig`, ...). The Atlas resolves each to the nearest explicit row above it in the same register and marks it inferred.")
w(f"- {weak['count']} Confirmed numbers have, after that resolution, neither a pin nor a tool with a version that the builder "
  f"could read. First ones: {', '.join(weak['ids'][:12])}. Grade C asks for a named tool and version, so these are worth a look; "
  "some will be the builder's parser missing a name.")
w(f"- {F['instrument strings fully named']} of {c['Instrument']} instrument strings were read completely (every part a tool, "
  "a pin or a date). The commonest parts left as notes: "
  + ", ".join(f"`{k}` ({v})" for k, v in F["unnamed instrument parts"][:10]) + ".")
w("")
w("### 3.3 Versions and pins under the numbers")
w("")
table(["tool", "numbers per version"],
      [[k, ", ".join(f"{ver}: {n}" for ver, n in v.items())] for k, v in F["tool versions under the numbers"].items()])
table(["repository", "commits", "numbers per commit (largest first)"],
      [[k, len(v), ", ".join(f"`{sha}`: {n}" for sha, n in list(v.items())[:6]) + (" ..." if len(v) > 6 else "")]
       for k, v in F["pins under the numbers"].items()])
w(f"The chapters read `x3d.loom` at {len(F['x3d.loom commits the chapters read'])} different commits; this Atlas read it at "
  f"`{F['x3d.loom commit this Atlas read']}`. A number holds at its own pin; this table is the worklist for a re-run at "
  "today's pins, not a list of errors.")
w("")
w("### 3.4 Laws and failure modes are mostly joined by prose")
w("")
orph = F["failure modes linked to no law"]
w(f"- {orph['count']} of {c['FailureMode']} failure modes are linked to no law by number, in either direction. "
  f"{len(F['laws with no failure mode cited by number'])} laws cite no failure mode by number: "
  + ", ".join(str(x) for x in F["laws with no failure mode cited by number"]) + ". They name their incidents by source tag instead.")
w(f"- Checks: {F['check kinds'].get('code', 0)} laws have a mechanical check, {F['check kinds'].get('process', 0)} have review only. "
  "Review-only laws with the most linked failures: "
  + ", ".join(f"law {r['law']} ({r['failure modes']})" for r in F["process-only laws ranked by failures"][:6]) + ".")
w(f"- {c['Diagnostic']} diagnostic codes and {c['TrapRule']} trap rules are named. Diagnostics named in LOOM-v1 but in no law's "
  "check column: " + ", ".join(f"`{d['code']}`" for d in F["diagnostics"] if not d["laws"]) + ".")
w(f"- Recurrences written down: " + ", ".join(f"{a} as {b}" for a, b in F["recurrences"]) + ".")
w("")
table(["class", "failure modes", "linked to no law"],
      [[r["name"], r["failure modes"], r["linked to no law"]] for r in F["failure classes"]])
w("### 3.5 The ledgers rarely cite each other by id")
w("")
h = F["heuristics whose evidence cites no id"]
w(f"- {sum(h['by grade'].values())} of {c['Heuristic']} heuristics have an evidence column that cites no stable id "
  f"({', '.join(f'{g} {n}' for g, n in h['by grade'].items())}); their evidence is prose the graph cannot follow.")
w(f"- {F['numbers cited by nothing']} of {T['numbers']} numbers are cited by id from no heuristic, drill or other number.")
w(f"- Edges that join ledgers: evidencedBy {F['edges'].get('evidencedBy', 0)}, mentions {F['edges'].get('mentions', 0)}, "
  f"paidForBy {F['edges'].get('paidForBy', 0)}, fixedByLaw {F['edges'].get('fixedByLaw', 0)}, carriedFrom {F['edges'].get('carriedFrom', 0)}. "
  "The ids exist; the habit of using them inside the cells does not yet.")
w("")
w("### 3.6 Source text to fix")
w("")
for kind, rows in F["findings"].items():
    for r in rows:
        w(f"- **{kind}**: " + ", ".join(f"{k} `{v}`" for k, v in r.items()))
w("")
w("### 3.7 Drills with no recorded run")
w("")
w(", ".join(f"`{d.split()[0]}`" for d in F["drills not run"]) + ".")
w("")
w("## 4. Limits")
w("")
w("- The Atlas checks that it copied the ledgers faithfully. It does not re-run any number.")
w("- Tools, versions and pins are read from free text with a small grammar; "
  f"{c['Instrument'] - F['instrument strings fully named']} of {c['Instrument']} instrument strings are pointers or keep parts as notes.")
w("- `law N` and `failure mode N` are found by pattern. A sentence such as \"law 40 and 123\" is ambiguous and is reported, not guessed.")
w("- Failure classes (K1 to K11) and themes (A to J) are chapter 02's grouping, graded Likely there.")
w("- The namespace is a placeholder (`.example`), as x3d.ML's is. No file is signed; the receipt binds results to file hashes only.")
(OUT / "FINDINGS.md").write_text("\n".join(W) + "\n", encoding="utf-8")
print(f"wrote out/FINDINGS.md, {len(W)} lines")
