import assert from 'node:assert/strict';
import fs from 'node:fs';
import {binding,sha256,qualifyControls,countReuses,snapshotXML} from '../evidence-lab/model.mjs';
const read=name=>fs.readFileSync(new URL('../'+name,import.meta.url));
const raw=read('evidence-lab/cases.json'),data=JSON.parse(raw),manifest=JSON.parse(read('evidence-lab/cases.manifest.json'));
assert.equal(await sha256(raw),manifest.sha256);assert.equal(raw.length,manifest.bytes);
assert.equal(await sha256(read('evidence-lab/build_lab.py')),data.producer_sha256);
assert.equal(await sha256(read(data.guard.path)),data.guard.sha256);
assert.equal(await sha256(read('evidence-lab/instruments.x3d')),manifest.scene_sha256);
for(const row of data.fixtures)assert.equal(await sha256(row.text),row.sha256);
const original=data.fixtures.find(f=>f.role==='positive');
assert.equal((await binding(original.text,original.sha256)).ok,true);
assert.equal((await binding(original.text+'\n',original.sha256)).ok,false);
assert.equal((await binding(original.text+'\n',await sha256(original.text+'\n'))).ok,true);
assert.equal(qualifyControls(data.fixtures).qualified,true);
assert.equal(qualifyControls(data.fixtures,{strategy:'always-pass'}).false_accepts,2);
assert.equal(qualifyControls(data.fixtures,{strategy:'always-pass'}).qualified,false);
assert.equal(qualifyControls(data.fixtures,{strategy:'always-pass',includeNegative:false}).qualified,false);
assert.equal(qualifyControls(data.fixtures,{includeNegative:false}).qualified,false);
assert.throws(()=>qualifyControls([...data.fixtures,data.fixtures[0]]),/Duplicate/);
const qualified={qualifiedGuard:data.guard.sha256};
const row={id:'one',guard:data.guard.sha256,target:'music',input_sha256:original.sha256,input_bound:true,accepted:true};
assert.equal(countReuses([row,{...row,id:'retry'},{...row,id:'renamed'}],qualified).distinct_consumptions,1);
assert.equal(countReuses([row,{...row,id:'another',target:'physics',input_sha256:data.fixtures.at(-1).sha256}],qualified).distinct_consumptions,2);
for(const changes of [{target:'gamedev'},{input_bound:false},{accepted:false}])assert.equal(countReuses([{...row,...changes}],qualified).distinct_consumptions,0);
assert.equal(countReuses([row],{...qualified,qualified:false}).distinct_consumptions,0);
for(const changes of [{target:'imaginary'},{input_bound:'false'},{accepted:'true'},{guard:'unbound-name'}])assert.throws(()=>countReuses([{...row,...changes}],qualified),/Malformed/);
assert.throws(()=>countReuses([row,row],qualified),/Duplicate/);
assert.equal(countReuses([{...row,guard:'f'.repeat(64)}],qualified).distinct_consumptions,0);
assert.throws(()=>countReuses([row]),/missing qualified guard/);
const note='C:\\research\\new\n$& <tag> "quoted"',xml=snapshotXML(new TextDecoder().decode(read('evidence-lab/instruments.x3d')),{note});
assert(xml.includes('gobbler.intervention-observation'));assert(xml.includes('&lt;tag&gt;'));assert(xml.includes('$&amp;'));assert(xml.includes('\\n'));
const html=new TextDecoder().decode(read('evidence-lab/index.html')),app=new TextDecoder().decode(read('evidence-lab/app.mjs'));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);assert.equal(ids.length,new Set(ids).size);
for(const [,id] of app.matchAll(/\$\('([^']+)'\)/g))assert(ids.includes(id),'Missing UI target '+id);
assert(!/<x3d-canvas[^>]*\bsrc=/.test(html));
console.log(JSON.stringify({status:'pass',fixtures:data.fixtures.length,experiments:3,scope:'Actual Web Crypto byte controls, positive/negative discrimination, content-based retry identity, malformed records, export literals and static UI targets. Not native browser execution.'}));
